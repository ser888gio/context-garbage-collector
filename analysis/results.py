import sys
from pathlib import Path

import pandas as pd

from analysis.report import load

HEADER = "Generated by `python -m analysis.results` — do not edit by hand."
CELL = ["model", "task_family", "strategy", "hints", "pressure"]


def join(values):
    return ", ".join(str(v) for v in sorted(values.unique()))


def experiments(df):
    df = df.assign(tag=df.tag.replace("", "untagged"), date=df.ts.astype(str).str[:10])
    return df.groupby(["tag", "model", "task_family"]).agg(
        first=("date", "min"), last=("date", "max"), runs=("run_id", "size"), strategies=("strategy", join),
        hints=("hints", join), pressure=("pressure", join), cost_usd=("cost_usd", "sum")).reset_index()


def by_collector(df):
    df = df.assign(est_ratio=(df.max_est_tokens / df.max_context_tokens).where(df.max_context_tokens > 0),
                   api_error=df.end == "api_error")
    return df.groupby(CELL).agg(
        runs=("success", "size"), success_rate=("success", "mean"), oom=("oom", "sum"), api_error=("api_error", "sum"),
        input_tokens=("input_tokens", "mean"), recalls=("recalls", "mean"), cache_breaks=("cache_breaks", "mean"),
        stable_prefix_share=("stable_prefix_share", "mean"), excess_tokens=("excess_tokens", "mean"),
        est_ratio=("est_ratio", "mean")).reset_index()


def render(path):
    df = load(path)
    md = lambda t: t.to_markdown(index=False, floatfmt=".2f")
    return f"{HEADER}\n\n## Experiments\n\n{md(experiments(df))}\n\n## Results by collector\n\n{md(by_collector(df))}\n"


if __name__ == "__main__":
    Path("docs/RESULTS.md").write_text(render(sys.argv[1] if len(sys.argv) > 1 else "results/runs.jsonl"), encoding="utf-8")
