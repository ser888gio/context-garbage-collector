def test_render_writes_header_and_one_row_per_experiment_with_untagged_fallback(tmp_path):
    path = tmp_path / "runs.jsonl"
    path.write_text("\n".join(json.dumps(r) for r in ROWS))

    out = results.render(path).splitlines()

    assert out[0] == "Generated by `python -m analysis.results` — do not edit by hand."
    assert [c.strip() for c in out[6].strip("|").split("|")] == [
        "s2", "m", "needle", "2026-11-12", "2026-11-13", "2", "oracle, truncate", "True", "False", "0.75"]
    assert [c.strip() for c in out[7].strip("|").split("|")] == [
        "untagged", "m", "needle", "2026-11-11", "2026-11-11", "1", "none", "False", "False", "0.00"]


def test_collector_row_counts_errors_and_ratio_skips_zero_context(tmp_path):
    path = tmp_path / "runs.jsonl"
    path.write_text("\n".join(json.dumps(r) for r in ROWS))

    out = results.render(path).splitlines()
    rows = {r.split("|")[3].strip(): [c.strip() for c in r.strip("|").split("|")] for r in out[13:]}

    assert rows["oracle"] == ["m", "needle", "oracle", "True", "False", "1", "1.00", "0", "0", "100.00", "0.00", "1.00", "0.50", "0.00", "0.50"]
    assert rows["truncate"] == ["m", "needle", "truncate", "True", "False", "1", "0.00", "0", "1", "200.00", "2.00", "3.00", "0.25", "10.00", "nan"]
    assert rows["none"][:11] == ["m", "needle", "none", "False", "False", "1", "1.00", "1", "0", "300.00", "nan"]
